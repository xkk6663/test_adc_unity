/**
 * @file    battery.h
 * @brief   电池电压采集模块 —— 被测模块头文件
 *
 * @details 本模块面向飞控板 2S 锂电池电压采集场景：
 *          - ADC 为 12 位（0~4095），参考电压 3.3V
 *          - 通过 3:1 分压电阻将电池电压降到 ADC 可测范围
 *          - 可测最大电压 = 3.3V × 3 = 9.9V，覆盖 2S 锂电池满电 8.4V
 *
 *          单元测试重点验证：
 *          1. adc_to_mv() 的换算正确性与边界钳位（函数健全性）
 *          2. read_battery_mv() 对 HAL 接口的调用顺序/参数/次数，
 *             以及 HAL 异常时的容错处理（接口交互正确性）
 */
#ifndef BATTERY_H
#define BATTERY_H

#include <stdint.h>

/* ==========================================================================
 * 硬件参数配置（根据实际电路板修改）
 * ========================================================================== */

/** @brief 12 位 ADC 满量程值 */
#define ADC_RAW_MAX        4095u

/** @brief ADC 参考电压，单位 mV（3.3V） */
#define ADC_REF_MV         3300u

/**
 * @brief 分压电阻比例（电池电压 : ADC 引脚电压）
 * @note  3:1 分压意味着电池电压 = ADC 测得电压 × 3
 */
#define BATTERY_DIVIDER    3u

/* ==========================================================================
 * 电池电压有效范围（钳位阈值）
 * ========================================================================== */

/** @brief 电压下限，单位 mV（防御性钳位，正常采样不会触发） */
#define BATTERY_MIN_MV     0u

/**
 * @brief 电压上限，单位 mV
 * @note  2S 锂电池满电电压为 8.4V；超过此值视为过压或采样异常，
 *        函数会钳位到该最大值，防止后续逻辑使用异常电压。
 */
#define BATTERY_MAX_MV     8400u

/* ==========================================================================
 * 错误码
 * ========================================================================== */

/**
 * @brief HAL 读取失败时 read_battery_mv() 的返回值
 * @note  使用 int32_t 返回类型是为了能区分"合法电压（≥0）"和"错误（-1）"
 */
#define BATTERY_READ_ERROR  (-1)

/* ==========================================================================
 * 对外接口
 * ========================================================================== */

/**
 * @brief 将 ADC 原始值换算为电池电压（mV），并做边界钳位
 *
 * @param[in] adc_raw  ADC 原始值，正常范围 0~4095
 *
 * @return  电池电压，单位 mV；结果被钳位在 [BATTERY_MIN_MV, BATTERY_MAX_MV]
 *
 * @details 换算公式：
 *          1. ADC 引脚测得电压 = adc_raw × ADC_REF_MV / ADC_RAW_MAX
 *          2. 电池电压 = ADC 引脚测得电压 × BATTERY_DIVIDER
 *          3. 对结果做上下限钳位
 *
 * @note    本函数为纯软件逻辑（不依赖硬件），是单元测试的主要被测对象。
 */
uint16_t adc_to_mv(uint16_t adc_raw);

/**
 * @brief 读取电池电压：调用 HAL 获取 ADC 原始值，换算并做容错处理
 *
 * @return  电池电压，单位 mV（≥0）；HAL 读取失败时返回 BATTERY_READ_ERROR (-1)
 *
 * @details 执行流程：
 *          1. 调用 HAL_ADC_GetValue() 获取 ADC 原始值
 *          2. 若返回 HAL_ADC_ERROR，说明硬件读取失败，返回 BATTERY_READ_ERROR
 *          3. 否则调用 adc_to_mv() 换算并返回
 *
 * @note    本函数依赖 HAL 接口，单元测试时用 CMock 桩替换 HAL，
 *          可验证：调用次数、调用顺序、返回值处理、错误容错。
 */
int32_t read_battery_mv(void);

#endif /* BATTERY_H */
