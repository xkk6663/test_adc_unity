/**
 * @file    led.h
 * @brief   LED 指示灯控制模块 —— 新增被测模块头文件
 *
 * @details 本模块根据电池电压控制两个 LED 的状态：
 *          - 电压 < 6000mV  → 红灯亮（低压警告）
 *          - 6000mV ~ 8400mV → 绿灯亮（正常）
 *          - 电压 > 8400mV  → 红灯亮（过压警告）
 *
 *          本模块依赖 hal_gpio.h 中的 HAL_GPIO_SetPin() 接口，
 *          是演示"新增模块如何接入单元测试体系"的示例。
 */
#ifndef LED_H
#define LED_H

#include <stdint.h>

/* ==========================================================================
 * 宏定义：电压阈值
 * ========================================================================== */

#define LED_LOW_VOLTAGE_MV  6000  ///< 低压阈值：低于此值亮红灯
#define LED_MAX_VOLTAGE_MV  8400  ///< 过压阈值：高于此值亮红灯（2S 满电）

/* ==========================================================================
 * 类型定义：LED 状态
 * ========================================================================== */

/**
 * @brief LED 整体状态
 */
typedef enum {
    LED_STATE_OFF   = 0,  ///< 全部熄灭（初始状态）
    LED_STATE_RED   = 1,  ///< 红灯亮（低压或过压警告）
    LED_STATE_GREEN = 2   ///< 绿灯亮（正常电压范围）
} led_state_t;

/* ==========================================================================
 * 接口函数声明
 * ========================================================================== */

/**
 * @brief 根据电池电压设置 LED 状态
 *
 * @param[in] battery_mv  电池电压（mV）
 *
 * @details 电压区间划分：
 *          - battery_mv < 6000        → 红灯亮，绿灯灭（低压）
 *          - 6000 ≤ battery_mv ≤ 8400 → 绿灯亮，红灯灭（正常）
 *          - battery_mv > 8400        → 红灯亮，绿灯灭（过压）
 *
 * @note    本函数调用 HAL_GPIO_SetPin() 控制硬件，
 *          单元测试中用 CMock 桩验证调用次数和参数。
 */
void led_set_by_voltage(uint16_t battery_mv);

/**
 * @brief 获取当前 LED 状态
 *
 * @return  当前 LED 状态（led_state_t）
 *
 * @note    用于测试验证：调用 led_set_by_voltage() 后，
 *          通过此函数确认内部状态是否正确更新。
 */
led_state_t led_get_state(void);

#endif /* LED_H */
